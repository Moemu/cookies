-- Insights owns Miyun connection state, controlled product queries, crawl jobs,
-- the current material projection, append-only data-card snapshots, and handoffs.
-- Third-party protocol DTOs remain in internal/integrations/crawler; authorized
-- media import idempotency remains in the Assets-owned asset_external_imports.

CREATE TABLE IF NOT EXISTS insight_miyun_connections (
  id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  organization_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  project_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  session_ciphertext VARBINARY(4096) NOT NULL,
  session_key_version VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  session_expires_at DATETIME(6) NULL,
  status VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'unverified',
  last_verified_at DATETIME(6) NULL,
  last_successful_request_at DATETIME(6) NULL,
  last_error_kind VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  last_error_code VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
  last_error_at DATETIME(6) NULL,
  version BIGINT NOT NULL DEFAULT 1,
  created_by VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL,

  UNIQUE KEY uq_insight_miyun_connections_scope (organization_id, id),
  UNIQUE KEY uq_insight_miyun_connections_project_scope (organization_id, project_id, id),
  KEY idx_insight_miyun_connections_project (organization_id, project_id, status, updated_at),
  CONSTRAINT fk_insight_miyun_connections_project FOREIGN KEY (organization_id, project_id) REFERENCES projects(organization_id, id),
  CONSTRAINT chk_insight_miyun_connections_status CHECK (status IN ('unverified', 'ready', 'auth_required', 'disabled')),
  CONSTRAINT chk_insight_miyun_connections_version CHECK (version > 0),
  CONSTRAINT chk_insight_miyun_connections_ciphertext CHECK (OCTET_LENGTH(session_ciphertext) > 0),
  CONSTRAINT chk_insight_miyun_connections_error_pair CHECK ((last_error_kind IS NULL AND last_error_code IS NULL) OR (last_error_kind IS NOT NULL AND last_error_code IS NOT NULL))
);

