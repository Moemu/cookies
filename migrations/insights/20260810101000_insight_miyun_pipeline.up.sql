  CONSTRAINT chk_insight_miyun_product_profiles_context CHECK (project_context_version > 0),
  CONSTRAINT chk_insight_miyun_product_profiles_window CHECK (window_start <= window_end),
  CONSTRAINT chk_insight_miyun_product_profiles_confirmed CHECK (status <> 'confirmed' OR (confirmed_by IS NOT NULL AND confirmed_at IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS insight_miyun_crawl_jobs (
  id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  organization_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  project_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  connection_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  product_profile_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  operation VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  query_schema_version VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  query_snapshot JSON NOT NULL,
  status VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'queued',
  completed_pages BIGINT UNSIGNED NOT NULL DEFAULT 0,
  discovered_count BIGINT UNSIGNED NOT NULL DEFAULT 0,
  deduplicated_count BIGINT UNSIGNED NOT NULL DEFAULT 0,
  downloaded_count BIGINT UNSIGNED NOT NULL DEFAULT 0,
  failed_count BIGINT UNSIGNED NOT NULL DEFAULT 0,
  cooldown_until DATETIME(6) NULL,
  last_error_kind VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  last_error_code VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
  version BIGINT NOT NULL DEFAULT 1,
  created_by VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL,

  UNIQUE KEY uq_insight_miyun_crawl_jobs_scope (organization_id, id),
  UNIQUE KEY uq_insight_miyun_crawl_jobs_project_scope (organization_id, project_id, id),
  KEY idx_insight_miyun_crawl_jobs_claim (organization_id, project_id, status, cooldown_until, created_at),
  CONSTRAINT fk_insight_miyun_crawl_jobs_project FOREIGN KEY (organization_id, project_id) REFERENCES projects(organization_id, id),
  CONSTRAINT fk_insight_miyun_crawl_jobs_connection FOREIGN KEY (organization_id, project_id, connection_id) REFERENCES insight_miyun_connections(organization_id, project_id, id),
  CONSTRAINT fk_insight_miyun_crawl_jobs_profile FOREIGN KEY (organization_id, project_id, product_profile_id) REFERENCES insight_miyun_product_profiles(organization_id, project_id, id),
  CONSTRAINT chk_insight_miyun_crawl_jobs_status CHECK (status IN ('queued', 'running', 'cooling_down', 'auth_required', 'partial', 'succeeded', 'failed', 'cancelled')),
  CONSTRAINT chk_insight_miyun_crawl_jobs_operation CHECK (operation IN ('product', 'cid')),
  CONSTRAINT chk_insight_miyun_crawl_jobs_version CHECK (version > 0),
  CONSTRAINT chk_insight_miyun_crawl_jobs_cooldown CHECK (status <> 'cooling_down' OR cooldown_until IS NOT NULL),
  CONSTRAINT chk_insight_miyun_crawl_jobs_error_pair CHECK ((last_error_kind IS NULL AND last_error_code IS NULL) OR (last_error_kind IS NOT NULL AND last_error_code IS NOT NULL))
);

-- Existing insight_assets has an organization-scoped identity key. The extra
-- composite key lets Miyun current projections enforce Project isolation too.
ALTER TABLE insight_assets
  ADD UNIQUE KEY uq_insight_assets_project_scope (organization_id, project_id, id);

CREATE TABLE IF NOT EXISTS insight_miyun_materials (
