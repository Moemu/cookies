  miyun_material_id VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  resource_id VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '',
  source_ref VARCHAR(1024) NOT NULL DEFAULT '',
  title VARCHAR(512) NOT NULL DEFAULT '',
  selection_status VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'discovered',
  import_status VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'pending',
  external_import_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NULL,
  platform_asset_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NULL,
  platform_asset_version BIGINT NULL,
  insight_asset_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NULL,
  version BIGINT NOT NULL DEFAULT 1,
  created_by VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  created_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL,

  UNIQUE KEY uq_insight_miyun_materials_scope (organization_id, id),
  UNIQUE KEY uq_insight_miyun_materials_project_scope (organization_id, project_id, id),
  UNIQUE KEY uq_insight_miyun_materials_source (organization_id, project_id, miyun_material_id),
  KEY idx_insight_miyun_materials_job (organization_id, project_id, first_seen_crawl_job_id, updated_at),
  KEY idx_insight_miyun_materials_import (organization_id, project_id, import_status, updated_at),
  CONSTRAINT fk_insight_miyun_materials_project FOREIGN KEY (organization_id, project_id) REFERENCES projects(organization_id, id),
  CONSTRAINT fk_insight_miyun_materials_job FOREIGN KEY (organization_id, project_id, first_seen_crawl_job_id) REFERENCES insight_miyun_crawl_jobs(organization_id, project_id, id),
  CONSTRAINT fk_insight_miyun_materials_external_import FOREIGN KEY (organization_id, project_id, external_import_id) REFERENCES asset_external_imports(organization_id, project_id, id),
  CONSTRAINT fk_insight_miyun_materials_asset_version FOREIGN KEY (organization_id, platform_asset_id, platform_asset_version) REFERENCES asset_versions(organization_id, asset_id, version),
  CONSTRAINT fk_insight_miyun_materials_project_asset FOREIGN KEY (organization_id, project_id, platform_asset_id, platform_asset_version) REFERENCES project_assets(organization_id, project_id, asset_id, asset_version),
  CONSTRAINT fk_insight_miyun_materials_insight_asset FOREIGN KEY (organization_id, project_id, insight_asset_id) REFERENCES insight_assets(organization_id, project_id, id),
  CONSTRAINT chk_insight_miyun_materials_selection CHECK (selection_status IN ('discovered', 'confirmed', 'rejected')),
  CONSTRAINT chk_insight_miyun_materials_import CHECK (import_status IN ('pending', 'downloading', 'imported', 'deduplicated', 'failed', 'skipped')),
  CONSTRAINT chk_insight_miyun_materials_version CHECK (version > 0),
  CONSTRAINT chk_insight_miyun_materials_asset_pair CHECK ((platform_asset_id IS NULL AND platform_asset_version IS NULL) OR (platform_asset_id IS NOT NULL AND platform_asset_version IS NOT NULL)),
  CONSTRAINT chk_insight_miyun_materials_insight_asset_pair CHECK (insight_asset_id IS NULL OR (platform_asset_id IS NOT NULL AND platform_asset_version IS NOT NULL))
);

