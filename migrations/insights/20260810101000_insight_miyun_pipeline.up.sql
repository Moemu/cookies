  id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  organization_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  project_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  material_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  crawl_job_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  schema_version VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  captured_at DATETIME(6) NOT NULL,
  first_published_at DATETIME(6) NULL,
  last_published_at DATETIME(6) NULL,
  delivery_days BIGINT UNSIGNED NOT NULL DEFAULT 0,
  cumulative_impressions BIGINT UNSIGNED NOT NULL DEFAULT 0,
  related_ads BIGINT UNSIGNED NOT NULL DEFAULT 0,
  related_creators BIGINT UNSIGNED NOT NULL DEFAULT 0,
  material_score DECIMAL(10, 4) NOT NULL DEFAULT 0,
  views BIGINT UNSIGNED NOT NULL DEFAULT 0,
  likes BIGINT UNSIGNED NOT NULL DEFAULT 0,
  comments BIGINT UNSIGNED NOT NULL DEFAULT 0,
  shares BIGINT UNSIGNED NOT NULL DEFAULT 0,
  saves BIGINT UNSIGNED NOT NULL DEFAULT 0,
  sanitized_raw JSON NULL,
  created_at DATETIME(6) NOT NULL,

  UNIQUE KEY uq_insight_miyun_material_snapshots_scope (organization_id, id),
  KEY idx_insight_miyun_material_snapshots_history (organization_id, project_id, material_id, captured_at, id),
  CONSTRAINT fk_insight_miyun_material_snapshots_project FOREIGN KEY (organization_id, project_id) REFERENCES projects(organization_id, id),
  CONSTRAINT fk_insight_miyun_material_snapshots_material FOREIGN KEY (organization_id, project_id, material_id) REFERENCES insight_miyun_materials(organization_id, project_id, id),
  CONSTRAINT fk_insight_miyun_material_snapshots_job FOREIGN KEY (organization_id, project_id, crawl_job_id) REFERENCES insight_miyun_crawl_jobs(organization_id, project_id, id),
  CONSTRAINT chk_insight_miyun_material_snapshots_score CHECK (material_score >= 0),
  CONSTRAINT chk_insight_miyun_material_snapshots_dates CHECK ((first_published_at IS NULL AND last_published_at IS NULL) OR (first_published_at IS NOT NULL AND last_published_at IS NOT NULL AND first_published_at <= last_published_at))
);

