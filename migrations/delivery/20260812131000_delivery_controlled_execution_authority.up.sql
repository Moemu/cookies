CREATE TABLE delivery_platform_entity_mappings (
  id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  organization_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  project_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  account_reference_id VARCHAR(160) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  plan_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  configuration_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  business_execution_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  computer_use_run_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  internal_object_kind VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  internal_object_id VARCHAR(160) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  platform_object_kind VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  platform_object_id VARCHAR(160) CHARACTER SET ascii COLLATE ascii_bin NULL,
  platform_status VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  result_evidence_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NULL,
  list_evidence_id VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NULL,
  status VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  version BIGINT NOT NULL,
  created_at DATETIME(6) NOT NULL,
  UNIQUE KEY uq_delivery_platform_mapping_scope (organization_id, project_id, id),
  UNIQUE KEY uq_delivery_platform_mapping_internal (organization_id, project_id, account_reference_id, internal_object_kind, internal_object_id),
  UNIQUE KEY uq_delivery_platform_mapping_external (organization_id, project_id, account_reference_id, platform_object_kind, platform_object_id),
  KEY idx_delivery_platform_mapping_run (organization_id, project_id, computer_use_run_id),
  CONSTRAINT fk_delivery_platform_mapping_execution FOREIGN KEY (organization_id, project_id, business_execution_id) REFERENCES delivery_controlled_executions(organization_id, project_id, id),
  CONSTRAINT chk_delivery_platform_mapping_status CHECK (status IN ('pending_verification','confirmed')),
  CONSTRAINT chk_delivery_platform_mapping_version CHECK (version > 0),
  CONSTRAINT chk_delivery_platform_mapping_confirmation CHECK (status <> 'confirmed' OR (platform_object_id IS NOT NULL AND platform_status IS NOT NULL AND result_evidence_id IS NOT NULL AND list_evidence_id IS NOT NULL))
);
